#pragma once

// U26 (darktower): the block-tick runtime of the tower devices. Custom Bedrock blocks have neither
// scheduled ticks nor block entities, so this unit keeps both for its own blocks:
//
//   scheduled ticks   Java's level.scheduleTick(pos, block, delay): one pending tick per position
//                     and block (a second schedule while one is pending is ignored, as Java's
//                     LevelTicks), run when due and the chunk is loaded, dropped when the block
//                     changed type; persisted in the world DB (gf:darktower:ticks).
//   device tickers    Java's BlockEntityTicker of the carminite builder, antibuilder, reactor,
//                     reactor debris and ghast trap: every server tick for each tracked position
//                     whose chunk is loaded; positions are tracked when the block is placed (any
//                     cause, gf::blockevents::onPlaced), generated by the dark tower, or first
//                     seen by a handler, and forgotten when the block is gone. The tracked
//                     positions are persisted (gf:darktower:devices); the per-device state is
//                     transient as in TF (none of these block entities saves its state, except
//                     the reactor debris' look, which the client renderer re-rolls).

#include <functional>
#include <string>

#include "core/GlobalPos.h"

class Block;
class BlockPos;
class BlockSource;

namespace gf::feature::darktower::runtime {

using core::GlobalPos;
using BlockFn = std::function<void(BlockSource& region, BlockPos const& pos, Block const& block)>;

/// Java's scheduleTick(pos, block, delay) for the block now at `pos`.
void schedule(BlockSource& region, BlockPos const& pos, int delay);
/// Whether a tick is pending at `pos`.
[[nodiscard]] bool scheduled(GlobalPos const& pos);
/// The handler of scheduled ticks of `blockId` (Block#tick).
void onTick(std::string const& blockId, BlockFn fn);

/// Starts ticking the device at `pos` (idempotent).
void track(BlockSource& region, BlockPos const& pos);
/// The device ticker of `blockId` (BlockEntityTicker).
void onDeviceTick(std::string const& blockId, BlockFn fn);
/// Called when a tracked device is forgotten (block gone or world closed): drop its state.
void onForget(std::string const& blockId, std::function<void(GlobalPos const&)> fn);
/// Whether a position is tracked (selftests).
[[nodiscard]] bool tracked(GlobalPos const& pos);

/// Installs the runtime (the module's install / uninstall).
void install();
void uninstall();

} // namespace gf::feature::darktower::runtime

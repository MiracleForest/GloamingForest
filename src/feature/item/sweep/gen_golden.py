# GloamingForest - generator of src/feature/item/sweep/Golden.inc (unit F9).
#
# Reads F13's oracle goldens tests/golden/loot.json (the block tables: what upstream 4.8 drops for the
# default state of each block, with an empty hand, shears and a silk touch pickaxe) and
# tests/golden/recipes.json (every recipe of upstream's data pack: type, result, ingredients), and from
# docs/spec/blockstates.md each block's owner and Java default state where Bedrock's default
# permutation differs (the first listed value), and writes
# the compact tables the in-game sweep selftests (src/feature/item/SweepTests.cpp) compare with.
#
#     python src/feature/item/sweep/gen_golden.py            # from the repository root
#     python src/feature/item/sweep/gen_golden.py --check    # exit 1 when Golden.inc is stale
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Golden.inc")


def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    loot = json.load(open(os.path.join(ROOT, "tests", "golden", "loot.json"), encoding="utf-8"))
    recipes = json.load(open(os.path.join(ROOT, "tests", "golden", "recipes.json"), encoding="utf-8"))
    rolls = loot["rolls"]
    owners, defaults = [], []
    for line in open(os.path.join(ROOT, "docs", "spec", "blockstates.md"), encoding="utf-8"):
        if not line.startswith("| `gloamingforest:"):
            continue
        cols = [x.strip() for x in line.strip().strip("|").split("|")]
        bid, owner, states, default = cols[0].strip("`"), cols[1], cols[3], cols[4]
        owners.append((bid, owner))
        if default in ("-", ""):
            continue
        names = [st.split("`")[1] for st in states.split("<br>") if st.startswith("`")]
        for kv in default.strip("`").split(","):
            k, v = kv.strip().split("=")
            full = next((n for n in names if n == k or n.endswith(":" + k)), k)
            defaults.append((bid, full, v))
    out = []
    out.append("// Generated by src/feature/item/sweep/gen_golden.py from F13's oracle goldens tests/golden/loot.json")
    out.append("// and tests/golden/recipes.json (upstream 4.8 @ 9e40a757 on NeoForge 1.21.1). Do not edit.")
    out.append("// clang-format off")
    out.append(f"inline constexpr int kGoldenRolls = {rolls};")
    out.append("/// One item of a block table's statistics: rolls containing it (of kGoldenRolls) and the per-roll count range.")
    out.append("struct GoldenDrop { char const* table; int tool; char const* item; int present; int min; int max; };")
    out.append("/// Tool 0: an empty hand, 1: shears, 2: a silk touch diamond pickaxe. A table without a row of a tool drops nothing with it.")
    out.append("inline constexpr char const* kGoldenBlockTables[] = {")
    tables = sorted(k for k, v in loot["tables"].items() if k.startswith("gloamingforest:blocks/"))
    for k in tables:
        out.append(f"    {c(k)},")
    out.append("};")
    out.append("inline constexpr GoldenDrop kGoldenDrops[] = {")
    for k in tables:
        t = loot["tables"][k]
        for tool, name in ((0, None), (1, "shears"), (2, "silk_touch")):
            if name is None or name in t.get("variantsSameAsDefault", []):
                stats = t
            else:
                stats = t["variants"].get(name)
                if stats is None:
                    stats = t
            for item, s in sorted(stats["items"].items()):
                out.append(f"    {{{c(k)}, {tool}, {c(item)}, {s['present']}, {s['min']}, {s['max']}}},")
    out.append("};")
    out.append("/// Each block's owner (docs/spec/blockstates.md).")
    out.append("struct GoldenOwner { char const* block; char const* owner; };")
    out.append("inline constexpr GoldenOwner kBlockOwners[] = {")
    for b, o in owners:
        out.append(f"    {{{c(b)}, {c(o)}}},")
    out.append("};")
    out.append("/// Java's default state where it is not Bedrock's default permutation (docs/spec/blockstates.md): the oracle's context.")
    out.append("struct GoldenDefault { char const* block; char const* state; char const* value; };")
    out.append("inline constexpr GoldenDefault kJavaDefaults[] = {")
    for b, k, v in defaults:
        out.append(f"    {{{c(b)}, {c(k)}, {c(v)}}},")
    out.append("};")
    out.append("/// A recipe of upstream's data pack: ingredients joined by ';' (an empty slot is empty), the item ids of one")
    out.append("/// ingredient by '|' (Java ids; tags expanded).")
    out.append("struct GoldenRecipe { char const* id; char const* type; char const* serializer; char const* result; int count; int width; int height; bool special; char const* ingredients; };")
    out.append("inline constexpr GoldenRecipe kGoldenRecipes[] = {")
    for k in sorted(recipes["recipes"]):
        r = recipes["recipes"][k]
        ing = ";".join("|".join(x) for x in r.get("ingredients", []))
        res = r.get("result") or ""
        out.append(
            f"    {{{c(k)}, {c(r['type'])}, {c(r['serializer'])}, {c(res)}, {r.get('count', 0)}, {r.get('width', 0)}, {r.get('height', 0)}, "
            f"{'true' if r.get('special') else 'false'}, {c(ing)}}},"
        )
    out.append("};")
    out.append("// clang-format on")
    text = "\n".join(out) + "\n"
    if "--check" in sys.argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("Golden.inc is stale: run python src/feature/item/sweep/gen_golden.py")
            return 1
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"wrote {OUT}: {len(tables)} block tables, {len(recipes['recipes'])} recipes")
    return 0


if __name__ == "__main__":
    sys.exit(main())

void installSigns() {
    for (auto family : {Family::Sign, Family::WallSign, Family::HangingSign, Family::WallHangingSign}) {
        for (auto const* e : entriesOf(family)) {
            ia::Match m;
            m.block = e->id;
            handlerIds().push_back(ia::onUseOn(m, useSign));
        }
    }
    static bool registered = false;
    if (registered) return;
    registered = true;
    screens::registerType({
        .id     = kScreen,
        .data   = editorData,
        .action = editorAction,
        .form   = editorForm,
        .closed = editorClosed,
    });
    for (auto family : {Family::Sign, Family::WallSign, Family::HangingSign, Family::WallHangingSign}) {
        for (auto const* e : entriesOf(family)) {
            // the sign breaks without its support, checked only when the neighbour on the side
            // Java's updateShape looks at changes (StandingSignBlock: below; WallSignBlock: behind;
            // CeilingHangingSignBlock: above; WallHangingSignBlock: either side along its board)
            blockevents::onNeighborChanged(e->id, [](BlockSource& region, BlockPos const& pos, BlockPos const& from) {
                Block const* b  = blockAt(region, pos);
                auto const*  se = b ? entryOf(*b) : nullptr;
                if (!isSign(se)) return;
                int dir = -1;
                for (int d = 0; d < 6; ++d) {
                    BlockPos n = offset(pos, d);
                    if (n.x == from.x && n.y == from.y && n.z == from.z) dir = d;
                }
                bool watched = false;
                switch (se->family) {
                case Family::Sign: watched = dir == Down; break;
                case Family::WallSign: watched = dir >= 0 && opposite(dir) == facingOf(*b); break;
                case Family::HangingSign: watched = dir == Up; break;
                case Family::WallHangingSign: watched = dir >= 0 && axisOf(dir) == axisOf(clockwise(facingOf(*b))); break;
                default: break;
                }
                if (!watched || signCanSurvive(region, pos, *b, *se)) return;
                log().info("families: {} at {} {} {} lost its support", se->id, pos.x, pos.y, pos.z);
                destroyWithDrops(region, pos);
            });
        }
    }
    // the display entities of a broken sign
    bd::onErase([](GlobalPos const& pos, Json const& doc, std::string const&) {
        if (!doc.contains(kKey)) return;
        displayed().erase(pos);
        syncText(pos, nullptr);
        if (!doc[kKey].contains("display")) return;
        for (auto const& [side, id] : doc[kKey]["display"].items()) {
            if (auto* a = entityById(id.is_number_integer() ? id.get<std::int64_t>() : 0)) a->remove();
        }
    });
    // a chunk that starts ticking: its signs' display entities, and stray ones
    detail::onChunkLoaded([](BlockSource& region, LevelChunk& chunk) {
        ChunkPos const cp  = chunk.mPosition;
        int            dim = static_cast<int>(region.getDimensionId());
        chunkTicked()[{dim, cp.x, cp.z}] = now();
        std::vector<GlobalPos> signs;
        bd::forEachInChunk(dim, cp.x, cp.z, [&](GlobalPos const& pos, Json const& doc) {
            if (doc.contains(kKey)) signs.push_back(pos);
        });
        for (auto const& p : signs) reconcileDisplay(p);
        sweepDisplays(region, chunk);
    });
    // the client mod draws the text of the signs it is told about
    net::onCompanionJoined([](Player& player) { sendAllTexts(player); });
}


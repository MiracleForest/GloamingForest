float signYaw(Block const& block, Entry const& e) {
    if (e.family == Family::Sign || e.family == Family::HangingSign) return static_cast<float>(intState(block, state::Rotation).value_or(0)) * 22.5f;
    static constexpr float toYRot[6]{0, 0, 180, 0, 90, 270}; // Direction.toYRot by FacingID: S 0, W 90, N 180, E 270
    int const              f = facingOf(block);
    return f >= 0 && f < 6 ? toYRot[f] : 0.0f;
}


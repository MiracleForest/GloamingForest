/// WallHangingSignBlock.canAttachTo: a wall hanging sign along the same axis, or a sturdy face.
bool hangingCanAttach(BlockSource& region, BlockPos const& at, int facing, int face) {
    Block const* b = blockAt(region, at);
    if (!b) return false;
    if (auto const* e = entryOf(*b); e && e->family == Family::WallHangingSign) return axisOf(facingOf(*b)) == axisOf(facing);
    return sturdy(region, at, face);
}

/// WallHangingSignBlock.canPlace: something to hang on at its clockwise or counter-clockwise side.
bool wallHangingCanPlace(BlockSource& region, BlockPos const& pos, int facing) {
    int cw = clockwise(facing), ccw = counterClockwise(facing);
    return hangingCanAttach(region, offset(pos, cw), facing, ccw) || hangingCanAttach(region, offset(pos, ccw), facing, cw);
}

/// CeilingHangingSignBlock.canSurvive: the face above has a sturdy centre. A hanging sign above is
/// one (Ceiling / WallHangingSignBlock.getBlockSupportShape is its outline, whose board reaches the
/// bottom): hanging signs chain.
bool hangingSupportAbove(BlockSource& region, BlockPos const& pos) {
    BlockPos above = offset(pos, Up);
    if (Block const* b = blockAt(region, above)) {
        if (auto const* e = entryOf(*b); e && (e->family == Family::HangingSign || e->family == Family::WallHangingSign)) return true;
        auto const& id = b->getTypeName();
        if (id.starts_with("minecraft:") && id.ends_with("_hanging_sign")) return true;
    }
    return sturdyCenter(region, above, Down);
}

/// The Java canSurvive of the sign at `pos`.
bool signCanSurvive(BlockSource& region, BlockPos const& pos, Block const& b, Entry const& e) {
    switch (e.family) {
    case Family::Sign: return solidAt(region, offset(pos, Down));                    // StandingSignBlock
    case Family::WallSign: return solidAt(region, offset(pos, opposite(facingOf(b)))); // WallSignBlock
    case Family::HangingSign: return hangingSupportAbove(region, pos);                 // CeilingHangingSignBlock
    case Family::WallHangingSign: return wallHangingCanPlace(region, pos, facingOf(b)); // WallHangingSignBlock.canSurvive
    default: return true;
    }
}

/// Java BlockPlaceContext.getNearestLookingDirections (the clicked face's opposite first).
std::array<int, 6> placeLooking(ia::PlaceContext const& c) {
    auto dirs = nearestLooking(c.player);
    if (c.clicked == c.pos || c.face < 0 || c.face > 5) return dirs;
    int want = opposite(c.face);
    int i    = 0;
    while (i < 6 && dirs[i] != want) ++i;
    if (i > 0 && i < 6) {
        for (int j = i; j > 0; --j) dirs[j] = dirs[j - 1];
        dirs[0] = want;
    }
    return dirs;
}


/// Java SignBlock.getYRotationDegrees: the direction the front text faces.
float signYaw(Block const& b, Entry const& e) {
    if (e.family == Family::Sign || e.family == Family::HangingSign) return intState(b, state::Rotation).value_or(0) * 22.5f;
    static constexpr float toYRot[6]{0, 0, 180, 0, 90, 270}; // Direction.toYRot: S 0, W 90, N 180, E 270
    return toYRot[facingOf(b)];
}

/// The centre of a side's text in the world (SignRenderer / HangingSignRenderer: the board centre,
/// just off the board on that side).
Vec3 textCentre(GlobalPos const& pos, Block const& b, Entry const& e, bool front) {
    // the front's normal from Java's yaw (0 south, 90 west)
    float yaw = signYaw(b, e) * std::numbers::pi_v<float> / 180.f;
    float nx = -std::sin(yaw), nz = std::cos(yaw);
    // the board: its height, its centre along the normal (a wall sign sits 0.4375 back:
    // translateSign's (0, -0.3125, -0.4375)) and half its thickness (2 model px, scaled 2/3)
    float y = 5.0f / 16, centre = 0, half = 1.0f / 16;
    if (e.family == Family::Sign) y = 13.33f / 16, half = 0.67f / 16;
    if (e.family == Family::WallSign) y = 8.33f / 16, centre = -0.4375f, half = 0.67f / 16;
    float along = centre + (front ? half + 0.04f : -half - 0.04f);
    return Vec3{pos.x + 0.5f + nx * along, pos.y + y, pos.z + 0.5f + nz * along};
}

/// A side's lines as a name tag (dye colours as format codes; black text shows white on the tag).
std::string nameTagOf(Json const& side) {
    static std::map<std::string, std::string> const colours{
        {"white", "§f"}, {"orange", "§6"}, {"magenta", "§d"}, {"light_blue", "§b"}, {"yellow", "§e"}, {"lime", "§a"}, {"pink", "§d"}, {"gray", "§8"},
        {"light_gray", "§7"}, {"cyan", "§3"}, {"purple", "§5"}, {"blue", "§9"}, {"brown", "§6"}, {"green", "§2"}, {"red", "§c"}, {"black", ""},
    };
    auto        it     = colours.find(side.value("color", std::string{"black"}));
    std::string prefix = it != colours.end() ? it->second : "";
    std::string out;
    auto        lines = side.value("lines", Json::array());
    for (std::size_t i = 0; i < static_cast<std::size_t>(kLines); ++i) {
        if (i) out += "\n";
        if (i < lines.size() && lines[i].is_string()) out += prefix + lines[i].get<std::string>();
    }
    return out;
}

Actor* entityById(std::int64_t uid) {
    if (uid == 0) return nullptr;
    auto level = ll::service::getLevel();
    if (!level) return nullptr;
    ActorUniqueID id;
    id.rawID = uid;
    return level->fetchEntity(id, false);
}

std::string displayTag(GlobalPos const& pos, bool front) {
    return std::string(kDisplayTag) + ":" + std::to_string(pos.dim) + ":" + std::to_string(pos.x) + ":" + std::to_string(pos.y) + ":" + std::to_string(pos.z) + (front ? ":front" : ":back");
}

Actor* spawnDisplay(BlockSource& region, Vec3 const& at) {
    auto& level = region.getLevel();
    auto  ctx   = level.getActorFactory().createSpawnedActor(ActorDefinitionIdentifier(std::string(kDisplayType)), nullptr, Vec3{at.x, at.y - 0.25f, at.z}, Vec2{0, 0});
    if (!ctx) return nullptr;
    return level.addEntity(region, std::move(ctx));
}

/// The display entities of the sign at `pos` match its text (created, renamed, moved, removed).
void reconcileDisplay(GlobalPos const& pos) {
    auto* region = regionOf(pos.dim);
    if (!region) return;
    BlockPos     bp = game::blockPos(pos);
    Block const* b  = blockAt(*region, bp);
    auto const*  e  = b ? entryOf(*b) : nullptr;
    if (!isSign(e)) return;
    auto const* raw = bd::get(*region, bp, kKey);
    if (!raw || !raw->is_object()) return; // no text ever written
    Json doc     = *raw;
    Json display = doc.value("display", Json::object());
    bool changed = false;
    for (bool front : {true, false}) {
        char const* key  = front ? "front" : "back";
        Json        side = doc.value(key, emptySide());
        Actor*      a    = entityById(display.value(key, std::int64_t{0}));
        if (!hasText(side)) {
            if (a) a->remove();
            if (display.contains(key)) {
                display.erase(key);
                changed = true;
            }
            continue;
        }
        Vec3 at = textCentre(pos, *b, *e, front);
        if (!a) {
            a = spawnDisplay(*region, at);
            if (!a) continue;
            a->addTag(kDisplayTag);
            a->addTag(displayTag(pos, front));
            display[key] = a->getOrCreateUniqueID().rawID;
            changed      = true;
        }
        auto tag = nameTagOf(side);
        if (a->getNameTag() != tag) a->setNameTag(tag);
        Vec3 want{at.x, at.y - 0.25f, at.z};
        auto const& now = a->getPosition();
        if (std::fabs(now.x - want.x) + std::fabs(now.y - want.y) + std::fabs(now.z - want.z) > 0.01f) a->teleportTo(want, true, 0, 1, false);
    }
    if (changed) {
        doc["display"] = display;
        bd::set(*region, bp, kKey, doc);
    }
}

/// Display entities left behind (their sign is gone, or names another entity): removed.
void sweepDisplays(BlockSource& region, LevelChunk& chunk) {
    ChunkPos const cp = chunk.mPosition;
    AABB box{Vec3{cp.x * 16.f, float(region.getMinHeight()), cp.z * 16.f}, Vec3{cp.x * 16.f + 16, float(region.getMaxHeight()), cp.z * 16.f + 16}};
    for (Actor* a : region.getEntities(box, 0.0f)) {
        if (!a || a->getTypeName() != kDisplayType) continue;
        bool keep = false;
        for (auto const& t : a->getTags()) {
            if (!t.starts_with(std::string(kDisplayTag) + ":")) continue;
            int  dim, x, y, z;
            char side[8]{};
            if (std::sscanf(t.c_str() + std::strlen(kDisplayTag) + 1, "%d:%d:%d:%d:%7s", &dim, &x, &y, &z, side) != 5) continue;
            auto const* raw = bd::get(GlobalPos{dim, x, y, z});
            auto const* s   = raw && raw->contains(kKey) ? &(*raw)[kKey] : nullptr;
            keep = s && s->contains("display") && (*s)["display"].value(side, std::int64_t{0}) == a->getOrCreateUniqueID().rawID;
        }
        if (!keep) a->remove();
    }
}

// ---- companions ---------------------------------------------------------------------------------

void sendText(Player& p, GlobalPos const& pos, Json const& doc) {
    Json clean = doc;
    clean.erase("display");
    net::send(p, "signs.text", {{"dim", pos.dim}, {"x", pos.x}, {"y", pos.y}, {"z", pos.z}, {"sign", clean}});
}

/// The chunks each companion has the signs of (dimension, chunk x, chunk z).
std::map<std::int64_t, std::set<std::tuple<int, int, int>>>& companionChunks() {
    static std::map<std::int64_t, std::set<std::tuple<int, int, int>>> m;
    return m;
}

/// A changed sign reaches the companions of its dimension that have its chunk.
void broadcast(GlobalPos const& pos, Json const& doc) {
    auto level = ll::service::getLevel();
    if (!level) return;
    auto chunk = std::make_tuple(pos.dim, pos.x >> 4, pos.z >> 4);
    level->forEachPlayer([&](Player& p) {
        if (!net::isCompanion(p) || static_cast<int>(p.getDimensionId()) != pos.dim) return true;
        auto it = companionChunks().find(p.getOrCreateUniqueID().rawID);
        if (it != companionChunks().end() && it->second.contains(chunk)) sendText(p, pos, doc);
        return true;
    });
}

/// Every 20 ticks: the signs of the chunks that came into a companion's range (Java sends block
/// entity data with the chunk).
void syncCompanions() {
    auto level = ll::service::getLevel();
    if (!level) return;
    std::set<std::int64_t> present;
    level->forEachPlayer([&](Player& p) {
        if (!net::isCompanion(p)) return true;
        auto uid = p.getOrCreateUniqueID().rawID;
        present.insert(uid);
        int   dim  = static_cast<int>(p.getDimensionId());
        auto  at   = p.getPosition();
        int   pcx  = static_cast<int>(std::floor(at.x)) >> 4, pcz = static_cast<int>(std::floor(at.z)) >> 4;
        auto& have = companionChunks()[uid];
        std::set<std::tuple<int, int, int>> now;
        for (int cx = pcx - kSyncChunks; cx <= pcx + kSyncChunks; ++cx)
            for (int cz = pcz - kSyncChunks; cz <= pcz + kSyncChunks; ++cz) now.insert({dim, cx, cz});
        for (auto const& c : now) {
            if (have.contains(c)) continue;
            bd::forEachInChunk(std::get<0>(c), std::get<1>(c), std::get<2>(c), [&p](GlobalPos const& pos, Json const& doc) {
                if (doc.contains(kKey)) sendText(p, pos, doc[kKey]);
            });
        }
        have = std::move(now);
        return true;
    });
    std::erase_if(companionChunks(), [&](auto const& kv) { return !present.contains(kv.first); });
}

void store(GlobalPos const& pos, Json doc) {
    auto* region = regionOf(pos.dim);
    if (!region) return;
    if (auto const* old = bd::get(*region, game::blockPos(pos), kKey); old && old->contains("display")) doc["display"] = (*old)["display"];
    bd::set(*region, game::blockPos(pos), kKey, doc);
    broadcast(pos, doc);
    reconcileDisplay(pos);
}

// ---- who may edit (SignBlockEntity.playerWhoMayEdit) ---------------------------------------------------

struct Editing {
    GlobalPos                               pos;
    bool                                    front = true;
    std::optional<std::vector<std::string>> draft; ///< the native editor's lines so far
};
std::map<std::int64_t, Editing>& editors() {
    static std::map<std::int64_t, Editing> m;
    return m;
}

/// SignBlock.otherPlayerIsEditingSign.
bool otherEditing(Player const& player, GlobalPos const& pos) {
    auto uid = const_cast<Player&>(player).getOrCreateUniqueID().rawID;
    for (auto const& [who, e] : editors())
        if (who != uid && e.pos == pos) return true;
    return false;
}

Player* playerById(std::int64_t uid) {
    auto* a = entityById(uid);
    return a && a->isPlayer() ? static_cast<Player*>(a) : nullptr;
}

/// SignBlockEntity.playerIsTooFarAwayToEdit: !player.canInteractWithBlock(pos, 4.0).
bool tooFar(Player& player, GlobalPos const& pos) {
    if (static_cast<int>(player.getDimensionId()) != pos.dim) return true;
    Vec3  eye = player.getEyePos();
    float dx  = std::max({float(pos.x) - eye.x, 0.f, eye.x - (pos.x + 1.f)});
    float dy  = std::max({float(pos.y) - eye.y, 0.f, eye.y - (pos.y + 1.f)});
    float dz  = std::max({float(pos.z) - eye.z, 0.f, eye.z - (pos.z + 1.f)});
    float r   = (player.isCreative() ? 5.0f : 4.5f) + 4.0f;
    return dx * dx + dy * dy + dz * dz >= r * r;
}

/// SignBlockEntity.updateSignText: only the player who may edit, a sign not waxed, a player who
/// may build; the record goes after the edit.
bool editText(Player& player, GlobalPos const& pos, bool front, std::vector<std::string> lines) {
    auto uid = player.getOrCreateUniqueID().rawID;
    auto it  = editors().find(uid);
    if (it == editors().end() || !(it->second.pos == pos) || it->second.front != front) {
        log().warn("families: {} tried to change a sign it may not edit ({} {} {})", player.getRealName(), pos.x, pos.y, pos.z);
        return false;
    }
    editors().erase(it);
    auto const* b = blockAt(pos);
    auto const* e = b ? entryOf(*b) : nullptr;
    if (!isSign(e) || docAt(pos).value("waxed", false) || !mayBuild(player) || tooFar(player, pos)) return false;
    for (auto& l : lines) l = fitLine(l, maxWidthOf(e));
    signs::setText(pos, lines, front);
    log().info("families: {} edited the sign at {} {} {}", player.getRealName(), pos.x, pos.y, pos.z);
    return true;
}

/// SignBlock.openTextEdit: records the editor, opens the native editor or the form.
void openEditor(Player& player, GlobalPos const& pos, bool front) {
    editors()[player.getOrCreateUniqueID().rawID] = {pos, front};
    if (!screens::open(player, kScreen, {{"pos", {pos.dim, pos.x, pos.y, pos.z}}, {"front", front}})) editors().erase(player.getOrCreateUniqueID().rawID);
}

GlobalPos posOf(Json const& ctx) {
    auto p = ctx.value("pos", Json::array());
    if (!p.is_array() || p.size() != 4) return {};
    return GlobalPos{p[0].get<int>(), p[1].get<int>(), p[2].get<int>(), p[3].get<int>()};
}

std::optional<Json> editorData(Player& player, Json const& ctx) {
    auto pos   = posOf(ctx);
    bool front = ctx.value("front", true);
    auto it    = editors().find(player.getOrCreateUniqueID().rawID);
    if (it == editors().end() || !(it->second.pos == pos) || it->second.front != front) return std::nullopt;
    auto const* b = blockAt(pos);
    auto const* e = b ? entryOf(*b) : nullptr;
    if (!isSign(e)) return std::nullopt;
    auto doc = docAt(pos);
    return Json{
        {"title", trFor(player, hanging(e) ? "hanging_sign.edit" : "sign.edit", hanging(e) ? "Edit Hanging Sign Message" : "Edit Sign Message")},
        {"lines", doc[front ? "front" : "back"]["lines"]},
        {"max_width", maxWidthOf(e)},
        {"hanging", hanging(e)},
    };
}

/// The native editor sends its lines as they change ("lines": SignEditScreen shows them on the sign
/// while typing) and when it is done; closing the screen commits the last lines, as Java's
/// SignEditScreen.removed sends them.
void editorAction(Player& player, Json const& ctx, Json const& action) {
    auto op = action.value("op", std::string{});
    std::vector<std::string> lines;
    for (auto const& l : action.value("lines", Json::array())) lines.push_back(l.is_string() ? l.get<std::string>() : "");
    if (op == "lines") {
        auto it = editors().find(player.getOrCreateUniqueID().rawID);
        if (it != editors().end()) it->second.draft = lines;
        return;
    }
    if (op != "done") return;
    editText(player, posOf(ctx), ctx.value("front", true), lines);
    screens::close(player, kScreen);
}

void editorClosed(Player& player, Json const& ctx) {
    auto it = editors().find(player.getOrCreateUniqueID().rawID);
    if (it == editors().end()) return;
    if (it->second.draft) {
        auto lines = *it->second.draft;
        editText(player, posOf(ctx), ctx.value("front", true), lines);
    } else {
        editors().erase(it);
    }
}

void editorForm(Player& player, Json const& ctx) {
    auto data = editorData(player, ctx);
    if (!data) return;
    auto lines = (*data)["lines"];
    ll::form::CustomForm form((*data)["title"].get<std::string>());
    for (int i = 0; i < kLines; ++i) {
        std::string current = i < static_cast<int>(lines.size()) && lines[i].is_string() ? lines[i].get<std::string>() : "";
        form.appendInput("line" + std::to_string(i), "", "", current);
    }
    auto pos   = posOf(ctx);
    bool front = ctx.value("front", true);
    form.sendTo(player, [pos, front](Player& p, ll::form::CustomFormResult const& result, ll::form::FormCancelReason) {
        if (!result) {
            editors().erase(p.getOrCreateUniqueID().rawID); // closed without an edit
            return;
        }
        std::vector<std::string> out;
        for (int i = 0; i < kLines; ++i) {
            auto it = result->find("line" + std::to_string(i));
            out.push_back(it != result->end() && std::holds_alternative<std::string>(it->second) ? std::get<std::string>(it->second) : "");
        }
        editText(p, pos, front, out);
    });
}

/// Every 20 ticks: SignBlockEntity.clearInvalidPlayerWhoMayEdit.
void clearInvalidEditors() {
    std::vector<std::int64_t> gone;
    for (auto const& [uid, e] : editors()) {
        auto* p = playerById(uid);
        if (!p || tooFar(*p, e.pos) || !isSign(blockAt(e.pos) ? entryOf(*blockAt(e.pos)) : nullptr)) gone.push_back(uid);
    }
    for (auto uid : gone) {
        if (auto* p = playerById(uid)) screens::close(*p, kScreen);
        editors().erase(uid);
    }
}


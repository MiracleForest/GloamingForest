/// SignItem / HangingSignItem placement (StandingAndWallBlockItem.getPlacementState).
void placeSign(ia::PlaceContext const& c) {
    auto const* e = entryOf(c.blockId);
    auto*       region = regionOf(c.pos.dim);
    if (!e || !region) return;
    if (e->family != Family::Sign && e->family != Family::HangingSign) return; // wall variants are not items
    BlockPos    bp    = game::blockPos(c.pos);
    bool        hang  = e->family == Family::HangingSign;
    auto const* wall  = e->str("wall").empty() ? nullptr : game::blockWith(e->str("wall"));
    auto const* wallE = wall ? entryOf(*wall) : nullptr;
    auto        looks = placeLooking(c);
    // the wall variant's own getStateForPlacement
    std::optional<int> wallFacing;
    if (wall && wallE) {
        for (int d : looks) {
            if (!horizontal(d)) continue;
            if (hang) {
                if (horizontal(c.face) && axisOf(d) == axisOf(c.face)) continue; // not along the clicked face's axis
                if (wallHangingCanPlace(*region, bp, opposite(d))) {
                    wallFacing = opposite(d);
                    break;
                }
            } else if (solidAt(*region, offset(bp, d))) { // WallSignBlock: facing d.getOpposite(), the block behind
                wallFacing = opposite(d);
                break;
            }
        }
    }
    int  attachment = hang ? Up : Down;
    Json standing;
    if (hang) {
        // CeilingHangingSignBlock.getStateForPlacement
        BlockPos     abovePos = offset(bp, Up);
        Block const* above    = blockAt(*region, abovePos);
        auto const*  aboveE   = above ? entryOf(*above) : nullptr;
        int          look     = lookDir(c.player);
        bool         attached = !sturdy(*region, abovePos, Down) || c.sneaking;
        if (aboveE && (aboveE->family == Family::HangingSign || aboveE->family == Family::WallHangingSign) && !c.sneaking) {
            if (aboveE->family == Family::WallHangingSign) {
                if (axisOf(facingOf(*above)) == axisOf(look)) attached = false;
            } else if (int r = intState(*above, state::Rotation).value_or(1); r % 4 == 0 && axisOf(from2D(r / 4)) == axisOf(look)) {
                attached = false;
            }
        }
        int rot = !attached ? to2D(opposite(look)) * 4 : rotationSegment(yawOf(c.player) + 180.0f);
        standing = {{state::Rotation, rot}, {state::Attached, attached}};
    } else {
        standing = {{state::Rotation, rotationSegment(yawOf(c.player) + 180.0f)}}; // StandingSignBlock
    }
    bool placed = false;
    for (int d : looks) {
        if (d == opposite(attachment)) continue;
        if (d == attachment) {
            Block const* now = blockAt(*region, bp);
            if (!now) break;
            auto const* s = withStates(*now, standing);
            if (s && signCanSurvive(*region, bp, *s, *e)) {
                game::setBlock(*region, bp, *s);
                placed = true;
                break;
            }
        } else if (wallFacing) {
            auto const* s = withStates(*wall, {{state::Facing, dirName(*wallFacing)}});
            if (s && signCanSurvive(*region, bp, *s, *wallE)) {
                game::setBlock(*region, bp, *s);
                placed = true;
                break;
            }
        }
    }
    if (!placed) {
        game::clearBlock(*region, bp);
        if (!c.player.isCreative()) give(c.player, makeItem(c.itemId.empty() ? c.blockId : c.itemId));
        log().info("families: {} could not be placed at {} {} {}", c.blockId, bp.x, bp.y, bp.z);
        return;
    }
    // SignItem.updateCustomBlockEntityTag: the placer edits the front
    if (ia::isServerPlayer(c.player)) openEditor(c.player, c.pos, true);
}

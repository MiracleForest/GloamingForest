constexpr char kKey[]          = "sign";
constexpr char kScreen[]       = "families.sign";
constexpr char kDisplayType[]  = "gloamingforest:sign_text";
constexpr char kDisplayTag[]   = "gf_sign_text";
constexpr int  kLines          = 4;
constexpr int  kMaxLineChars   = 384; // ServerboundSignUpdatePacket.MAX_STRING_LENGTH
constexpr int  kSyncChunks     = 10;  // companions get the signs of the chunks this close

bool isSign(Entry const* e) {
    return e && (e->family == Family::Sign || e->family == Family::WallSign || e->family == Family::HangingSign || e->family == Family::WallHangingSign);
}
bool hanging(Entry const* e) { return e && (e->family == Family::HangingSign || e->family == Family::WallHangingSign); }

Json emptySide() { return {{"lines", Json::array({"", "", "", ""})}, {"color", "black"}, {"glowing", false}}; }

Json docAt(GlobalPos const& pos) {
    auto* region = regionOf(pos.dim);
    if (!region) return Json();
    auto const* j = bd::get(*region, game::blockPos(pos), kKey);
    Json        d = j && j->is_object() ? *j : Json::object();
    if (!d.contains("front") || !d["front"].is_object()) d["front"] = emptySide();
    if (!d.contains("back") || !d["back"].is_object()) d["back"] = emptySide();
    if (!d.contains("waxed")) d["waxed"] = false;
    return d;
}

bool hasText(Json const& side) {
    for (auto const& l : side.value("lines", Json::array()))
        if (l.is_string() && !l.get<std::string>().empty()) return true;
    return false;
}

// ---- Java's sign line width (Font.width over the default font's ASCII advances) ----------------------

int charWidth(unsigned char c) {
    switch (c) {
    case '!': case '\'': case ',': case '.': case ':': case ';': case '|': case 'i': return 2;
    case '`': case 'l': return 3;
    case ' ': case 'I': case '[': case ']': case 't': return 4;
    case '"': case '(': case ')': case '*': case '<': case '>': case 'f': case 'k': case '{': case '}': return 5;
    case '@': case '~': return 7;
    default: return c < 0x80 ? 6 : 9;
    }
}

/// The line cut where Java's SignEditScreen stops typing (line width in font pixels).
std::string fitLine(std::string const& line, int maxWidth) {
    std::string out;
    int         width = 0;
    for (std::size_t i = 0; i < line.size() && out.size() < static_cast<std::size_t>(kMaxLineChars);) {
        unsigned char c   = static_cast<unsigned char>(line[i]);
        std::size_t   len = c < 0x80 ? 1 : (c >> 5) == 6 ? 2 : (c >> 4) == 14 ? 3 : 4;
        if (c == '\n' || c == '\r') break;
        int w = charWidth(c);
        if (width + w > maxWidth) break;
        width += w;
        out.append(line, i, len);
        i += len;
    }
    return out;
}

int maxWidthOf(Entry const* e) { return hanging(e) ? 60 : 90; } // HangingSignBlockEntity.MAX_TEXT_LINE_WIDTH


/// SignBlockEntity.isFacingFrontText: the player relative to the sign's hitbox centre
/// (WallSignBlock.getSignHitboxCenterPosition: its AABB's centre).
bool facingFront(Block const& b, Entry const& e, GlobalPos const& pos, Player const& player) {
    float cx = 0.5f, cz = 0.5f;
    if (e.family == Family::WallSign) {
        switch (facingOf(b)) {
        case North: cz = 15.f / 16; break;
        case South: cz = 1.f / 16; break;
        case East: cx = 1.f / 16; break;
        case West: cx = 15.f / 16; break;
        default: break;
        }
    }
    auto   p     = player.getPosition();
    double dx    = p.x - (pos.x + cx), dz = p.z - (pos.z + cz);
    float  yaw   = signYaw(b, e);
    float  angle = static_cast<float>(std::atan2(dz, dx) * 180.0 / std::numbers::pi) - 90.0f;
    float  diff  = std::fmod(std::fabs(yaw - angle), 360.0f);
    if (diff > 180.0f) diff = 360.0f - diff;
    return diff <= 90.0f;
}

/// Java's SignApplicator items.
bool isApplicator(std::string const& id) {
    return id == "minecraft:honeycomb" || id == "minecraft:glow_ink_sac" || id == "minecraft:ink_sac" || (id.starts_with("minecraft:") && id.ends_with("_dye"));
}

/// SignApplicator.canApplyToSign / tryApplyToSign. True when applied.
bool applyItem(Player& player, GlobalPos const& pos, std::string const& itemId, ItemStack const& item, bool front) {
    auto  doc  = docAt(pos);
    auto& side = doc[front ? "front" : "back"];
    auto* region = regionOf(pos.dim);
    if (!region) return false;
    BlockPos bp = game::blockPos(pos);
    if (itemId == "minecraft:honeycomb") {
        doc["waxed"] = true; // HoneycombItem: SoundEvents.HONEYCOMB_WAX_ON, levelEvent 3003
        bedrockSound(*region, bp, "copper.wax.on");
    } else if (itemId == "minecraft:glow_ink_sac") {
        if (!hasText(side) || side.value("glowing", false)) return false;
        side["glowing"] = true;
        bedrockSound(*region, bp, "sign.ink_sac.use");
    } else if (itemId == "minecraft:ink_sac") {
        if (!hasText(side) || !side.value("glowing", false)) return false;
        side["glowing"] = false;
        bedrockSound(*region, bp, "sign.ink_sac.use");
    } else {
        auto color = itemId.substr(10, itemId.size() - 14); // minecraft:<color>_dye
        if (!hasText(side) || side.value("color", "black") == color) return false;
        side["color"] = color;
        bedrockSound(*region, bp, "sign.dye.use");
    }
    store(pos, doc);
    consumeHeld(player, item);
    return true;
}

ia::Result useSign(ia::UseOnContext const& c) {
    if (c.sneaking && !c.itemId.empty()) return ia::Result::Pass;
    auto const* e = entryOf(c.block);
    if (!e) return ia::Result::Pass;
    if (repeatedUse(c.player, c.pos, c.firstEvent)) return ia::Result::Consume;
    bool front = facingFront(c.block, *e, c.pos, c.player);
    bool waxed = docAt(c.pos).value("waxed", false);
    if (!c.itemId.empty()) {
        // SignBlock.useItemOn: an applicator acts (or nothing happens); other items go on to their
        // own use (SKIP_DEFAULT_BLOCK_INTERACTION)
        if (!isApplicator(c.itemId)) return ia::Result::Pass;
        if (mayBuild(c.player) && !waxed && !otherEditing(c.player, c.pos)) applyItem(c.player, c.pos, c.itemId, c.item, front);
        return ia::Result::Consume;
    }
    // SignBlock.useWithoutItem
    if (waxed) {
        bedrockSound(c.player.getDimensionBlockSource(), game::blockPos(c.pos), "block.sign.waxed_interact_fail");
        return ia::Result::Consume;
    }
    if (otherEditing(c.player, c.pos) || !mayBuild(c.player)) return ia::Result::Pass;
    openEditor(c.player, c.pos, front);
    return ia::Result::Consume;
}


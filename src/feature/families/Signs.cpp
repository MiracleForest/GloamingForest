/// The changes of this tick, sent to the companions once at its end (flushTexts): the signs whose
/// text changed and the signs whose text went.
struct PendingTexts {
    std::map<GlobalPos, Json> signs;
    std::set<GlobalPos>       gone;
};
PendingTexts& pendingTexts() {
    static PendingTexts p;
    return p;
}

Json posJson(GlobalPos const& p) { return Json::array({p.dim, p.x, p.y, p.z}); }

constexpr std::size_t kBatch = 64; ///< signs per message

/// The players of this world named by sendText's log line (cleared with the world).
std::set<std::int64_t>& loggedCompanions() {
    static std::set<std::int64_t> s;
    return s;
}

/// Sends `payload` on the sign text channel to `player` (a companion; net::send refuses others), with
/// one host log line for each real player first sent sign text (e2e: never a vanilla client).
void sendText(Player& player, Json const& payload) {
    if (!net::send(player, kTextChannel, payload) || player.isSimulatedPlayer()) return;
    if (loggedCompanions().insert(player.getOrCreateUniqueID().rawID).second) log().info("families: sign text sent to the companion {}", player.getRealName());
}

/// Sends `payload` on the sign text channel to every companion (vanilla clients get nothing).
void sendToCompanions(Json const& payload) {
    auto level = ll::service::getLevel();
    if (!level) return;
    level->forEachPlayer([&payload](Player& p) {
        if (net::isCompanion(p)) sendText(p, payload);
        return true;
    });
}

/// The companions' copy of the text of the sign at `pos` follows `text` (nullptr: no sign or no
/// text there): queued when it changed and sent at the end of the tick (SignBlockEntity.setChanged's
/// update packet), so a chunk full of signs that loads costs one message per companion.
void syncText(GlobalPos const& pos, Json const* text) {
    auto& sent    = sentTexts();
    auto& pending = pendingTexts();
    auto  it      = sent.find(pos);
    if (!text) {
        if (it == sent.end()) return;
        sent.erase(it);
        pending.signs.erase(pos);
        pending.gone.insert(pos);
        return;
    }
    if (it != sent.end() && it->second == *text) return;
    sent[pos] = *text;
    pending.gone.erase(pos);
    pending.signs[pos] = *text;
}

/// A sign whose chunk unloaded: forgotten until the chunk loads again, by the companions too (their
/// copy goes, so the client mod's list holds only the signs of loaded chunks; the load sends it
/// again).
void forgetUnloaded(GlobalPos const& pos) {
    displayed().erase(pos);
    if (sentTexts().erase(pos) == 0) return;
    pendingTexts().signs.erase(pos);
    pendingTexts().gone.insert(pos);
}

/// Sends this tick's changes to every companion: {"signs": [...], "gone": [...]}, at most 64 entries
/// a message.
void flushTexts() {
    auto& pending = pendingTexts();
    if (pending.signs.empty() && pending.gone.empty()) return;
    Json signs = Json::array();
    Json gone  = Json::array();
    auto flush = [&] {
        if (signs.empty() && gone.empty()) return;
        Json msg = Json::object();
        if (!signs.empty()) msg["signs"] = std::move(signs);
        if (!gone.empty()) msg["gone"] = std::move(gone);
        sendToCompanions(msg);
        signs = Json::array();
        gone  = Json::array();
    };
    for (auto const& pos : pending.gone) {
        gone.push_back(posJson(pos));
        if (signs.size() + gone.size() >= kBatch) flush();
    }
    for (auto& [pos, text] : pending.signs) {
        Json entry   = std::move(text);
        entry["pos"] = posJson(pos);
        signs.push_back(std::move(entry));
        if (signs.size() + gone.size() >= kBatch) flush();
    }
    flush();
    pending.signs.clear();
    pending.gone.clear();
}

/// A companion that joins gets the text of every sign (in batches of 64 signs).
void sendAllTexts(Player& player) {
    Json batch = Json::array();
    auto flush = [&] {
        if (batch.empty()) return;
        sendText(player, {{"signs", batch}});
        batch = Json::array();
    };
    for (auto const& [pos, text] : sentTexts()) {
        if (pendingTexts().signs.contains(pos)) continue; // the end of the tick sends it to every companion
        Json entry   = text;
        entry["pos"] = posJson(pos);
        batch.push_back(std::move(entry));
        if (batch.size() >= kBatch) flush();
    }
    flush();
}

/// The display entities of the sign at `pos` match its text (created, renamed, moved, removed),
/// and so does the client mod's copy of it.
void reconcileDisplay(GlobalPos const& pos) {
    auto* region = regionOf(pos.dim);
    if (!region) return;
    BlockPos     bp = game::blockPos(pos);
    Block const* b  = blockAt(*region, bp);
    auto const*  e  = b ? entryOf(*b) : nullptr;
    if (!isSign(e)) {
        displayed().erase(pos);
        syncText(pos, nullptr);
        return;
    }
    auto const* raw = bd::get(*region, bp, kKey);
    if (!raw || !raw->is_object()) { // no text ever written
        displayed().erase(pos);
        syncText(pos, nullptr);
        return;
    }
    Json doc     = *raw;
    Json display = doc.value("display", Json::object());
    bool changed = false;
    for (bool front : {true, false}) {
        char const* key  = front ? "front" : "back";
        Json        side = doc.value(key, emptySide());
        Actor*      a    = entityById(display.value(key, std::int64_t{0}));
        if (a && !a->isAlive()) { // killed (/kill): a new one replaces it
            a->remove();
            a = nullptr;
        }
        if (!hasText(side)) {
            if (a) a->remove();
            if (display.contains(key)) {
                display.erase(key);
                changed = true;
            }
            continue;
        }
        Vec3 at = textCentre(pos, *b, *e, front);
        if (!a) {
            // one of ours that the record lost (it loaded after the record was rewritten): adopted
            auto tag = displayTag(pos, front);
            AABB near{Vec3{at.x - 1.5f, at.y - 1.5f, at.z - 1.5f}, Vec3{at.x + 1.5f, at.y + 1.5f, at.z + 1.5f}};
            for (Actor* o : region->getEntities(near, 0.0f)) {
                if (!o || !o->isAlive() || o->getTypeName() != kDisplayType || !o->hasTag(tag)) continue;
                a            = o;
                display[key] = a->getOrCreateUniqueID().rawID;
                changed      = true;
                break;
            }
        }
        if (!a) {
            a = spawnDisplay(*region, at);
            if (!a) continue;
            a->addTag(kDisplayTag);
            a->addTag(displayTag(pos, front));
            display[key] = a->getOrCreateUniqueID().rawID;
            changed      = true;
        }
        auto tag = nameTagOf(side);
        if (a->getNameTag() != tag) {
            a->setNameTag(tag);
            renamedDisplays().insert(a->getOrCreateUniqueID().rawID);
        }
        // a name set by code leaves CanShowName off (a name tag item sets it): without it the
        // client draws no name; the nameable component's always_show shows it without looking at it
        if (!a->getStatusFlag(ActorFlags::CanShowName)) SynchedActorDataAccess::setActorFlag(a->getEntityContext(), ActorFlags::CanShowName, true);
        Vec3 want{at.x, at.y - 0.25f, at.z};
        auto const& now = a->getPosition();
        if (std::fabs(now.x - want.x) + std::fabs(now.y - want.y) + std::fabs(now.z - want.z) > 0.01f) a->teleportTo(want, true, 0, 1, false);
    }
    if (changed) {
        doc["display"] = display;
        bd::set(*region, bp, kKey, doc);
    }
    if (display.empty()) displayed().erase(pos);
    else displayed().insert(pos);
    // the companions' copy, with the display entities as they are now (the client mod hides the
    // name tags of exactly these)
    Json text = drawnText(doc, display);
    syncText(pos, hasText(text["front"]) || hasText(text["back"]) ? &text : nullptr);
}

/// The chunks whose first tick after a load was seen ((dim, chunk x, chunk z) -> fam::now()):
/// their entities have had time to load.
std::map<std::tuple<int, int, int>, std::int64_t>& chunkTicked() {
    static std::map<std::tuple<int, int, int>, std::int64_t> m;
    return m;
}

/// Every 20 ticks: the display entities of the signs in loaded chunks are still there and alive
/// (a sign whose chunk unloaded is checked again when the chunk ticks after its load). Only a
/// missing or dead entity costs a reconcile, and only 40 ticks after the chunk's load (its
/// entities load with it, a little later than its blocks).
void checkDisplays() {
    std::vector<GlobalPos> signs(displayed().begin(), displayed().end());
    auto                   tick = now();
    for (auto const& pos : signs) {
        auto* region = regionOf(pos.dim);
        if (!region || !region->hasChunksAt(game::blockPos(pos), 0, false)) {
            forgetUnloaded(pos);
            continue;
        }
        auto seen = chunkTicked().find({pos.dim, pos.x >> 4, pos.z >> 4});
        if (seen != chunkTicked().end() && tick - seen->second < 40) continue;
        auto const* raw = bd::get(*region, game::blockPos(pos), kKey);
        bool        ok  = raw && raw->is_object() && raw->contains("display");
        if (ok) {
            for (auto const& [side, id] : (*raw)["display"].items()) {
                auto* a = entityById(id.is_number_integer() ? id.get<std::int64_t>() : 0);
                if (!a || !a->isAlive()) ok = false;
            }
        }
        if (!ok) reconcileDisplay(pos);
    }
    std::erase_if(chunkTicked(), [tick](auto const& kv) { return tick - kv.second >= 40; });
    // a sign with text but no display entity (it could not be spawned) is not in displayed(): it
    // leaves the companions' list the same way when its chunk unloads
    std::vector<GlobalPos> unloaded;
    for (auto const& [pos, text] : sentTexts()) {
        if (displayed().contains(pos)) continue; // checked above
        auto* region = regionOf(pos.dim);
        if (!region || !region->hasChunksAt(game::blockPos(pos), 0, false)) unloaded.push_back(pos);
    }
    for (auto const& pos : unloaded) forgetUnloaded(pos);
}

/// Display entities left behind (their sign is gone, or names another entity): removed.
void sweepDisplays(BlockSource& region, LevelChunk& chunk) {
    ChunkPos const cp = chunk.mPosition;
    AABB box{Vec3{cp.x * 16.f, float(region.getMinHeight()), cp.z * 16.f}, Vec3{cp.x * 16.f + 16, float(region.getMaxHeight()), cp.z * 16.f + 16}};
    for (Actor* a : region.getEntities(box, 0.0f)) {
        if (!a || a->getTypeName() != kDisplayType) continue;
        bool keep = false;
        for (auto const& t : a->getTags()) {
            if (!t.starts_with(std::string(kDisplayTag) + ":")) continue;
            int  dim, x, y, z;
            char side[8]{};
            if (std::sscanf(t.c_str() + std::strlen(kDisplayTag) + 1, "%d:%d:%d:%d:%7s", &dim, &x, &y, &z, side) != 5) continue;
            auto const* raw = bd::get(GlobalPos{dim, x, y, z});
            auto const* s   = raw && raw->contains(kKey) ? &(*raw)[kKey] : nullptr;
            keep = s && s->contains("display") && (*s)["display"].value(side, std::int64_t{0}) == a->getOrCreateUniqueID().rawID;
        }
        if (!keep) a->remove();
    }
}

// ---- vanilla clients: only the side facing the viewer --------------------------------------------------

// Java draws each side's text flat on its own face of the board, so a viewer reads the side facing
// it and nothing of the other. A name tag faces every viewer and shows through the board, so each
// vanilla viewer's client is told to show the name of the side facing it and to hide the other's
// (an actor data packet of that display entity's name, sent to that viewer only; the server's own
// name stays the text, so a client that did not get it yet shows both, as before). The client mod
// hides these name tags and draws the text itself.

constexpr float kFacingRange = 64.0f; ///< blocks: viewers farther away keep the server's names
constexpr int   kFacingTicks = 4;     ///< the sides are chosen this often
constexpr int   kSettleTicks = 60;    ///< a viewer new to a sign is told again every 20 ticks this long (its client may add the entity later)
constexpr int   kResendTicks = 200;   ///< and every viewer again this often (an entity its client added again)

/// What a vanilla viewer's client was told of a display entity's name.
struct Told {
    bool         hidden   = false;
    std::int64_t since    = 0; ///< the tick the viewer came within range of it
    std::int64_t lastSent = 0;
};
/// (viewer, display entity) -> what was told (the viewers within range only).
std::map<std::pair<std::int64_t, std::int64_t>, Told>& toldViewers() {
    static std::map<std::pair<std::int64_t, std::int64_t>, Told> m;
    return m;
}
std::int64_t& namePacketsSent() {
    static std::int64_t n = 0;
    return n;
}
/// The real vanilla players named by sendDisplayName's log line (cleared with the world).
std::set<std::int64_t>& loggedViewers() {
    static std::set<std::int64_t> s;
    return s;
}

/// Tells `viewer`'s client the name of `display`: the server's (its text), or none.
void sendDisplayName(Player& viewer, Actor& display, bool hidden) {
    auto packet = MinecraftPackets::createPacket(MinecraftPacketIds::SetActorData);
    if (!packet) return;
    SetActorDataPacketPayload payload(display.getRuntimeID(), *display.mEntityData, nullptr, 0, true);
    auto&                     items = *payload.mPackedItems;
    std::erase_if(items, [](std::unique_ptr<DataItem> const& item) { return !item || item->getId() != static_cast<ushort>(ActorDataIDs::Name); });
    if (items.empty()) return;
    if (hidden) items.front()->setData(std::string{});
    static_cast<SetActorDataPacketPayload&>(static_cast<SetActorDataPacket&>(*packet)) = std::move(payload);
    packet->sendTo(viewer);
    ++namePacketsSent();
    // one host log line for each real vanilla player first told (e2e: never a companion)
    if (!viewer.isSimulatedPlayer() && loggedViewers().insert(viewer.getOrCreateUniqueID().rawID).second)
        log().info("families: the vanilla client {} is shown the sign sides facing it", viewer.getRealName());
}

/// One sign's display entities and its board (the centre and the front's normal).
struct SignSides {
    GlobalPos    pos;
    Vec3         centre;
    float        nx = 0, nz = 0;
    std::int64_t front = 0, back = 0;
};

/// Every vanilla viewer within range of a sign: the name of the side facing it shows, the other's is
/// hidden (edge on, both are). Told when the side changes, again while the viewer is new to the sign
/// and now and then (`resend`).
void chooseFacingSides(bool resend) {
    auto level = ll::service::getLevel();
    if (!level) return;
    // the vanilla viewers first: without any, nothing to choose (the client mod draws the text)
    std::vector<std::int64_t> viewers;
    level->forEachPlayer([&](Player& p) {
        if (!net::isCompanion(p)) viewers.push_back(p.getOrCreateUniqueID().rawID);
        return true;
    });
    if (viewers.empty() || displayed().empty()) {
        toldViewers().clear();
        renamedDisplays().clear();
        return;
    }
    std::vector<SignSides> signs;
    for (auto const& pos : displayed()) {
        auto* region = regionOf(pos.dim);
        if (!region || !region->hasChunksAt(game::blockPos(pos), 0, false)) continue;
        Block const* b = blockAt(*region, game::blockPos(pos));
        auto const*  e = b ? entryOf(*b) : nullptr;
        auto const*  raw = isSign(e) ? bd::get(*region, game::blockPos(pos), kKey) : nullptr;
        if (!raw || !raw->is_object() || !raw->contains("display")) continue;
        auto const& display = (*raw)["display"];
        SignSides   s;
        s.pos       = pos;
        s.front     = display.value("front", std::int64_t{0});
        s.back      = display.value("back", std::int64_t{0});
        float yaw   = signYaw(*b, *e) * std::numbers::pi_v<float> / 180.f;
        s.nx        = -std::sin(yaw);
        s.nz        = std::cos(yaw);
        Vec3 f = textCentre(pos, *b, *e, true), k = textCentre(pos, *b, *e, false);
        s.centre    = Vec3{(f.x + k.x) / 2, (f.y + k.y) / 2, (f.z + k.z) / 2};
        signs.push_back(s);
    }
    auto& told    = toldViewers();
    auto& renamed = renamedDisplays();
    auto  tick    = now();
    std::map<std::pair<std::int64_t, std::int64_t>, Told> next;
    level->forEachPlayer([&](Player& viewer) {
        if (net::isCompanion(viewer)) return true; // the client mod draws the text, the name tags hidden
        auto        uid = viewer.getOrCreateUniqueID().rawID;
        int         dim = static_cast<int>(viewer.getDimensionId());
        auto const& eye = viewer.getPosition(); // (a Bedrock player's position is its eyes)
        for (auto const& s : signs) {
            if (s.pos.dim != dim) continue;
            float dx = eye.x - s.centre.x, dy = eye.y - s.centre.y, dz = eye.z - s.centre.z;
            if (dx * dx + dy * dy + dz * dz > kFacingRange * kFacingRange) continue;
            float along = dx * s.nx + dz * s.nz; // > 0: in front of the board
            for (bool front : {true, false}) {
                auto id = front ? s.front : s.back;
                if (!id) continue;
                bool hidden = front ? along <= 0 : along >= 0;
                auto key    = std::make_pair(uid, id);
                Told t;
                t.hidden = hidden;
                t.since  = tick;
                bool send = true;
                if (auto it = told.find(key); it != told.end()) {
                    t.since    = it->second.since;
                    t.lastSent = it->second.lastSent;
                    bool fresh = tick - t.since <= kSettleTicks && tick - t.lastSent >= 20;
                    send       = it->second.hidden != hidden || renamed.contains(id) || fresh || resend || tick - t.lastSent >= kResendTicks;
                }
                if (send) {
                    if (auto* a = entityById(id)) {
                        sendDisplayName(viewer, *a, hidden);
                        t.lastSent = tick;
                    }
                }
                next[key] = t;
            }
        }
        return true;
    });
    told = std::move(next); // (a viewer out of range is told again when it comes back)
    renamed.clear();
}

void store(GlobalPos const& pos, Json doc) {
    auto* region = regionOf(pos.dim);
    if (!region) return;
    if (auto const* old = bd::get(*region, game::blockPos(pos), kKey); old && old->contains("display")) doc["display"] = (*old)["display"];
    bd::set(*region, game::blockPos(pos), kKey, doc);
    reconcileDisplay(pos);
}


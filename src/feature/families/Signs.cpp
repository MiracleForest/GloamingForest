// Contract "families+blockevents", sign text (F11; spike S3 backend: block data). TF's 32 signs
// (standing, wall, hanging and wall hanging signs of the eight woods) are custom blocks, which have
// no block entities: their text lives in block data (gf::blockdata key "sign"):
//
//     {"front": {"lines": ["", "", "", ""], "color": "black", "glowing": false},
//      "back":  {...}, "waxed": false, "display": {"front": <entity id>, "back": <entity id>}}
//
// Java's SignItem / HangingSignItem, SignBlock and SignBlockEntity behaviour:
// - placement: the standing / ceiling sign or its wall variant by the player's look and what it can
//   hang on (StandingAndWallBlockItem.getPlacementState, WallSignBlock / WallHangingSignBlock /
//   CeilingHangingSignBlock.getStateForPlacement), then the editor for the placer;
// - a sign without its support breaks (canSurvive / updateShape);
// - using a sign: dyes, glow ink, ink sac and honeycomb on the side facing the player; an empty
//   hand, any other item and an applicator that changes nothing open the editor (Java's
//   PASS_TO_DEFAULT_BLOCK_INTERACTION; sneaking with an item uses the item); a waxed sign takes
//   nothing (its fail sound);
// - the editor (gf::screens "families.sign": the client mod's native editor, a form for vanilla
//   clients) edits only for the player it was opened for (SignBlockEntity.playerWhoMayEdit), who
//   may build and stays within reach; lines are cut at Java's line width (90 px, hanging signs 60).
// Display:
// - client mod users: the text is drawn flat on the board as Java's SignRenderer /
//   HangingSignRenderer draw it (src/client/families/SignText.cpp); the server sends every
//   companion the text of each sign it knows ("families.sign_text": {"signs": [{"pos": [dim, x, y,
//   z], "front": side, "back": side, "display": [entity id, ...]}], "gone": [[dim, x, y, z]]}, side
//   = {"lines", "color", "glowing"}) when a sign with text loads or its text or display entities
//   change, "gone" when the sign or its text goes or its chunk unloads, and all of them when a
//   companion joins (SignBlockEntity's update packet; one host log line names each player first
//   sent sign text);
// - vanilla clients: the text shows as the name of an invisible entity in front of each written
//   side (the S3 fallback: gloamingforest:sign_text, generated by tools/families); each vanilla
//   viewer is shown only the name of the side facing it (an actor data packet to that viewer hides
//   the other's), as Java draws each side's text on its own face of the board. The text is the
//   size of the game's name tags (a name tag's text cannot be scaled to the board). The client mod
//   hides the name tags of the display entities a sign's message names (their unique ids) while it
//   draws the text itself.


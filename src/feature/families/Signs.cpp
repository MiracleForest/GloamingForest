// ---- the client mod's copy of the text (SignRenderer draws it) -----------------------------------------

/// What the client mod draws of a sign: the lines, colour and glow of both sides, and the unique ids
/// of the sign's display entities (`display`: {"front": id, "back": id}), whose name tags the client
/// mod hides while it draws the text (an entity is matched to its sign by id, not by where it
/// stands).
Json drawnText(Json const& doc, Json const& display) {
    auto side = [&doc](char const* key) {
        Json s = doc.value(key, emptySide());
        if (!s.is_object()) s = emptySide();
        return Json{{"lines", s.value("lines", Json::array())}, {"color", s.value("color", std::string{"black"})}, {"glowing", s.value("glowing", false)}};
    };
    Json entities = Json::array();
    if (display.is_object())
        for (auto const& [key, id] : display.items())
            if (id.is_number_integer() && id.get<std::int64_t>() != 0) entities.push_back(id.get<std::int64_t>());
    return {{"front", side("front")}, {"back", side("back")}, {"display", std::move(entities)}};
}


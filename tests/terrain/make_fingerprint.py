# GloamingForest - U2 (terrain): writes src/feature/terrain/GoldenFingerprint.inc from the F13 goldens
# (tests/golden/{biomes,heights,surface}/seed-*.json), the excerpt the in-game selftests
# terrain.height_golden / terrain.surface_golden compare with. Run from the repository root:
#     python tests/terrain/make_fingerprint.py
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SEEDS = [(0, "seed-0.json"), (123456789, "seed-123456789.json"), (-8346138912345678901, "seed-m8346138912345678901.json")]

# orientation of the golden grids (checked by the gtests: TerrainGolden.*)
BIOME_ROWS_ARE_Z = True   # main.rows[z][x]
HEIGHTS_I_MAJOR = True    # worldSurfaceWg[i][j], i along x
SURFACE_I_MAJOR = True

QW = 72          # quart window -36 .. 35 (sampleTerrain reaches 3 quarts)
QX0 = -36
HX0, HN, HSTEP = -128, 32, 8   # heights: blocks -128 .. 120
SC0, SN = -2, 4                # surface: chunks -2 .. 1
SX0, SSTEP = -32, 2
SW = (SN * 16) // SSTEP


def load(kind, name):
    with open(os.path.join(ROOT, "tests", "golden", kind, name), encoding="utf-8") as f:
        return json.load(f)


def at(grid, i, j, i_major):
    return grid[i][j] if i_major else grid[j][i]


out = ["// Generated by tests/terrain/make_fingerprint.py from the F13 goldens (tests/golden); do not edit.",
       "// Included by src/feature/terrain/SelfTests.cpp.", ""]
palette = None
chars = None
seeds_out = []
for seed, name in SEEDS:
    b = load("biomes", name)
    h = load("heights", name)
    s = load("surface", name)
    if palette is None:
        palette = b["palette"]
        chars = b["paletteChars"]
    m = b["main"]
    rows = m["rows"]
    biomes = []
    for j in range(QW):
        for i in range(QW):
            qx, qz = QX0 + i, QX0 + j
            x, z = qx - m["x0"], qz - m["z0"]
            biomes.append(rows[z][x] if BIOME_ROWS_ARE_Z else rows[x][z])
    ws, of = [], []
    for i in range(HN):
        for j in range(HN):
            gi = (HX0 + i * HSTEP - h["x0"]) // h["step"]
            gj = (HX0 + j * HSTEP - h["z0"]) // h["step"]
            ws.append(at(h["worldSurfaceWg"], gi, gj, HEIGHTS_I_MAJOR))
            of.append(at(h["oceanFloorWg"], gi, gj, HEIGHTS_I_MAJOR))
    cells = []
    spal = s["palette"]
    schars = s["paletteChars"]
    for i in range(SW):
        for j in range(SW):
            bx, bz = SX0 + i * SSTEP, SX0 + j * SSTEP
            gi = (bx - s["x0"]) // s["step"]
            gj = (bz - s["z0"]) // s["step"]
            height = at(s["worldSurfaceWg"], gi, gj, SURFACE_I_MAJOR)
            top_rows = s["top"]
            c = top_rows[gi][gj] if SURFACE_I_MAJOR else top_rows[gj][gi]
            cells.append((height, spal[schars.index(c)]))
    sname = str(seed).replace("-", "m")
    out.append("inline constexpr char kBiomes_%s[] = \"%s\";" % (sname, "".join(biomes)))
    out.append("inline constexpr short kWorldSurface_%s[] = {%s};" % (sname, ", ".join(map(str, ws))))
    out.append("inline constexpr short kOceanFloor_%s[] = {%s};" % (sname, ", ".join(map(str, of))))
    out.append("inline SurfaceCell const kSurface_%s[] = {%s};" % (sname, ", ".join('{%d, "%s"}' % c for c in cells)))
    seeds_out.append((seed, sname))

head = ["struct SurfaceCell {", "    short       height;", "    char const* top;", "};",
        "struct Fingerprint {",
        "    std::int64_t seed;",
        "    int qx0, qz0, qw, qh; char const* biomes; ///< main biome chars, [j * qw + i] at quart (qx0 + i, qz0 + j)",
        "    int hx0, hz0, hstep, hn; short const* worldSurface; short const* oceanFloor; ///< [i * hn + j] at (hx0 + i * hstep, hz0 + j * hstep)",
        "    int sc0, sn, sx0, sstep, sw; SurfaceCell const* surface; ///< chunks sc0 .. sc0 + sn - 1 (both axes); [i * sw + j] at (sx0 + i * sstep, sx0 + j * sstep)",
        "};",
        "inline constexpr char kBiomeChars[] = \"%s\";" % chars,
        "inline constexpr char const* kBiomePalette[] = {%s};" % ", ".join('"%s"' % p for p in palette), ""]
out[3:3] = head
fps = []
for seed, sname in seeds_out:
    lit = "%dLL" % seed if seed != -8346138912345678901 else "-8346138912345678900LL - 1"
    fps.append("    Fingerprint{%s, %d, %d, %d, %d, kBiomes_%s, %d, %d, %d, %d, kWorldSurface_%s, kOceanFloor_%s, %d, %d, %d, %d, %d, kSurface_%s}" % (
        lit, QX0, QX0, QW, QW, sname, HX0, HX0, HSTEP, HN, sname, sname, SC0, SN, SX0, SSTEP, SW, sname))
out.append("inline Fingerprint const kFingerprints[] = {\n%s,\n};" % ",\n".join(fps))
path = os.path.join(ROOT, "src", "feature", "terrain", "GoldenFingerprint.inc")
with open(path, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(out) + "\n")
print("wrote", path, os.path.getsize(path), "bytes")

// Writes tests/progression/TreeLayoutGolden.inc: the node positions Minecraft 1.21.1's own
// net.minecraft.advancements.TreeNodePosition computes (the layout ServerAdvancementManager#apply
// runs over every advancement tree and sends to the clients in DisplayInfo's x / y), for TF's
// advancement tree (data/twilightforest/advancement/*.json, children in file-name order) and for
// seeded random trees with display-less nodes. AdvancementNode keeps its children in a
// ReferenceOpenHashSet (identity order, different on every run); the oracle swaps it for a
// LinkedHashSet so the sibling order is the one the C++ test gives.
//
// Run against the oracle's NeoForge 1.21.1 server (tools/oracle/fetch.ps1), e.g.
//   $cp = (Get-Content <gf-oracle>/dumper/<hash>/javac.args)[7].Trim('"')
//   javac -cp $cp -d <out> TreeNodePositionOracle.java
//   java -cp "<out>;$cp" TreeNodePositionOracle <advancement dir> > ../TreeLayoutGolden.inc

import java.io.IOException;
import java.lang.reflect.Field;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.Random;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import net.minecraft.SharedConstants;
import net.minecraft.advancements.Advancement;
import net.minecraft.advancements.AdvancementHolder;
import net.minecraft.advancements.AdvancementNode;
import net.minecraft.advancements.AdvancementRequirements;
import net.minecraft.advancements.AdvancementRewards;
import net.minecraft.advancements.AdvancementType;
import net.minecraft.advancements.DisplayInfo;
import net.minecraft.advancements.TreeNodePosition;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.Bootstrap;
import net.minecraft.world.item.ItemStack;

public final class TreeNodePositionOracle {
    record In(String id, String parent, boolean display) {}

    static Field childrenField;

    static List<String> layout(String name, List<In> tree, StringBuilder out) throws Exception {
        Map<String, AdvancementNode> nodes = new LinkedHashMap<>();
        Map<String, DisplayInfo>     displays = new LinkedHashMap<>();
        AdvancementNode              root = null;
        // nodes are made parents first; the children are added afterwards in the given order
        List<In> created = new ArrayList<>();
        while (created.size() < tree.size())
            for (In n : tree)
                if (!created.contains(n) && (n.parent.isEmpty() || created.stream().anyMatch(o -> o.id.equals(n.parent)))) created.add(n);
        for (In n : created) {
            Optional<DisplayInfo> d = Optional.empty();
            if (n.display) {
                DisplayInfo di = new DisplayInfo(ItemStack.EMPTY, Component.literal(n.id), Component.literal(""), Optional.empty(), AdvancementType.TASK, false, false, false);
                displays.put(n.id, di);
                d = Optional.of(di);
            }
            Optional<ResourceLocation> parent = n.parent.isEmpty() ? Optional.empty() : Optional.of(ResourceLocation.parse(n.parent));
            Advancement     a = new Advancement(parent, d, AdvancementRewards.EMPTY, Map.of(), AdvancementRequirements.EMPTY, false);
            AdvancementNode p = n.parent.isEmpty() ? null : nodes.get(n.parent);
            AdvancementNode node = new AdvancementNode(new AdvancementHolder(ResourceLocation.parse(n.id), a), p);
            childrenField.set(node, new LinkedHashSet<AdvancementNode>());
            if (p == null) root = node;
            nodes.put(n.id, node);
        }
        for (In n : tree)
            if (!n.parent.isEmpty()) nodes.get(n.parent).addChild(nodes.get(n.id));
        TreeNodePosition.run(root);
        out.append("    {\"").append(name).append("\",\n     {");
        for (In n : tree) out.append("{\"").append(n.id).append("\", \"").append(n.parent).append("\", ").append(n.display).append("}, ");
        out.append("},\n     {");
        for (Map.Entry<String, DisplayInfo> e : displays.entrySet())
            out.append(String.format(Locale.ROOT, "{\"%s\", %.1ff, %sf}, ", e.getKey(), e.getValue().getX(), Float.toString(e.getValue().getY())));
        out.append("}},\n");
        return null;
    }

    public static void main(String[] args) throws Exception {
        SharedConstants.tryDetectVersion();
        Bootstrap.bootStrap();
        childrenField = AdvancementNode.class.getDeclaredField("children");
        childrenField.setAccessible(true);
        StringBuilder out = new StringBuilder();
        out.append("// Generated by tests/progression/oracle/TreeNodePositionOracle.java from Minecraft 1.21.1's\n");
        out.append("// net.minecraft.advancements.TreeNodePosition (NeoForge 21.1.209 server). Do not edit.\n");
        out.append("// {name, {{id, parent, hasDisplay}...}, {{id, x, y}...}}\n");
        // TF's tree, children in file-name order
        List<Path> files = new ArrayList<>();
        try (var s = Files.list(Path.of(args[0]))) {
            s.filter(p -> p.toString().endsWith(".json")).sorted((a, b) -> a.getFileName().toString().compareTo(b.getFileName().toString())).forEach(files::add);
        }
        Pattern parentRe = Pattern.compile("\"parent\"\\s*:\\s*\"([^\"]+)\"");
        List<In> tf = new ArrayList<>();
        for (Path f : files) {
            String id   = "twilightforest:" + f.getFileName().toString().replace(".json", "");
            String text = Files.readString(f);
            Matcher m = parentRe.matcher(text);
            tf.add(new In(id, m.find() ? m.group(1) : "", text.contains("\"display\"")));
        }
        layout("twilightforest", tf, out);
        // random trees
        for (int seed = 1; seed <= 40; ++seed) {
            Random   r = new Random(seed);
            int      n = 2 + r.nextInt(seed < 20 ? 14 : 45);
            List<In> t = new ArrayList<>();
            for (int i = 0; i < n; ++i) {
                String parent = i == 0 ? "" : "t:n" + r.nextInt(i);
                boolean display = i == 0 || r.nextInt(7) != 0;
                t.add(new In("t:n" + i, parent, display));
            }
            layout("random_" + seed, t, out);
        }
        System.out.print(out);
    }
}

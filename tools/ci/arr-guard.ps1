<#
.SYNOPSIS
  Rejects any file in the repository that is byte-identical to an All Rights Reserved file of The
  Twilight Forest (its .ogg sounds and music, its .nbt structure templates).

.DESCRIPTION
  Rules R10 / R11: GloamingForest regenerates TF's 229 .ogg and 274 .nbt files as originals;
  nobody opens, decodes or copies them. This guard compares git blob ids only: the list
  tools/ci/arr-blobs.txt holds "<blob id> <path>" for every *.ogg / *.nbt of the TF tree at the
  pinned commit, taken from the tree listing (git ls-tree) of the shared checkout. The blobs
  themselves are never downloaded (tools/tf/fetch.ps1 excludes them from its blob-less clone).

  Checked: every file of HEAD (committed), every staged file, and (-WorkingTree, the default
  locally) every modified or untracked file of the working tree.

  -Refresh rewrites tools/ci/arr-blobs.txt from the local TF checkout's tree listing; without it,
  a present checkout is used to verify the committed list.

  Exit code 0 = clean, 1 = a match (or a stale list).

.EXAMPLE
  pwsh tools/ci/arr-guard.ps1
  pwsh tools/ci/arr-guard.ps1 -Refresh
#>
param(
    [switch]$Refresh,
    [switch]$CommittedOnly,
    [string]$TfDir
)
$ErrorActionPreference = 'Stop'
$root = (Resolve-Path "$PSScriptRoot/../..").Path
$Commit = '9e40a75721c716b2fdf80c16d1058fe718825e9f'
$list = Join-Path $PSScriptRoot 'arr-blobs.txt'
if (-not $TfDir) { $TfDir = if ($env:GF_TF_HOME) { $env:GF_TF_HOME } else { Join-Path $env:LOCALAPPDATA 'gf-tf' } }

function Get-TfArrListing {
    if (-not (Test-Path (Join-Path $TfDir '.git'))) { return $null }
    # the tree listing only: names and blob ids, no blob content
    $env:GIT_NO_LAZY_FETCH = '1'
    try {
        $lines = & git -C $TfDir ls-tree -r --full-tree $Commit 2>$null
        if ($LASTEXITCODE -ne 0) { return $null }
    } finally { Remove-Item Env:GIT_NO_LAZY_FETCH -ErrorAction SilentlyContinue }
    $out = foreach ($l in $lines) {
        if ($l -match '^\d+ blob ([0-9a-f]{40})\t(.+\.(ogg|nbt))$') { "$($Matches[1]) $($Matches[2])" }
    }
    return @($out | Sort-Object { $_.Substring(41) })
}

$header = "# All Rights Reserved files of TF 4.8 ($Commit): git blob id and path, from the tree listing. Generated by tools/ci/arr-guard.ps1 -Refresh."
if ($Refresh) {
    $tf = Get-TfArrListing
    if (-not $tf) { Write-Host "[arr-guard] TF checkout not found at $TfDir (run pwsh tools/tf/fetch.ps1)" -ForegroundColor Red; exit 1 }
    [IO.File]::WriteAllText($list, (@($header) + $tf -join "`n") + "`n")
    Write-Host "[arr-guard] wrote $($tf.Count) entries to $list"
    exit 0
}
if (-not (Test-Path $list)) { Write-Host "[arr-guard] $list is missing (pwsh tools/ci/arr-guard.ps1 -Refresh)" -ForegroundColor Red; exit 1 }
$arr = @{}
foreach ($l in Get-Content $list) {
    if ($l -match '^([0-9a-f]{40}) (.+)$') { $arr[$Matches[1]] = $Matches[2] }
}
$failures = [Collections.Generic.List[string]]::new()
$tf = Get-TfArrListing
if ($tf) {
    $committed = @(Get-Content $list | Where-Object { $_ -notmatch '^#' })
    if (($committed -join "`n") -ne ($tf -join "`n")) { $failures.Add('tools/ci/arr-blobs.txt differs from the TF tree listing (pwsh tools/ci/arr-guard.ps1 -Refresh)') }
}

# blob ids of the repository: HEAD, the index, and changed / untracked working tree files
$blobs = @{}
foreach ($l in & git -C $root ls-tree -r HEAD) {
    if ($l -match '^\d+ blob ([0-9a-f]{40})\t(.+)$') { $blobs["HEAD:$($Matches[2])"] = $Matches[1] }
}
foreach ($l in & git -C $root ls-files -s) {
    if ($l -match '^\d+ ([0-9a-f]{40}) \d\t(.+)$') { $blobs["index:$($Matches[2])"] = $Matches[1] }
}
if (-not $CommittedOnly) {
    $changed = @(& git -C $root ls-files --modified --others --exclude-standard) | Where-Object { $_ -and (Test-Path (Join-Path $root $_) -PathType Leaf) }
    if ($changed) {
        $hashes = @($changed | & git -C $root hash-object --stdin-paths)
        for ($i = 0; $i -lt $changed.Count; $i++) { $blobs["worktree:$($changed[$i])"] = $hashes[$i] }
    }
}
foreach ($k in $blobs.Keys) {
    if ($arr.ContainsKey($blobs[$k])) { $failures.Add("$k is byte-identical to the All Rights Reserved TF file $($arr[$blobs[$k]])") }
}
if ($failures.Count) {
    Write-Host '[arr-guard] FAILED:' -ForegroundColor Red
    $failures | ForEach-Object { Write-Host "  - $_" -ForegroundColor Red }
    exit 1
}
Write-Host "[arr-guard] OK: $($blobs.Count) repository blobs checked against $($arr.Count) ARR blob ids" -ForegroundColor Green
exit 0

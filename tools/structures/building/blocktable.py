import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SPEC = os.path.join(ROOT, "docs", "spec", "building.md")
OUT = os.path.join(ROOT, "src", "feature", "building", "BlockTable.inc")
OUT_CUT = os.path.join(ROOT, "src", "feature", "building", "StonecutTable.inc")

TOOLS = ("pickaxe", "axe", "shovel", "hoe")
TIERS = ("stone", "iron", "diamond")


def rows():
    out = {}
    with open(SPEC, encoding="utf-8") as f:
        text = f.read()
    section = text[text.index("### Blocks ("):text.index("### Items (")]
    for line in section.splitlines():
        m = re.match(r"^\| `twilightforest:([a-z_0-9]+)` \|", line)
        if not m:
            continue
        cells = line.split("|")
        out[m.group(1)] = (cells[3], cells[-2])
    return out


def strength(reg, table, raw):
    m = re.search(r"ofFullCopy\(([A-Z_]+)\.get\(\)\)", reg)
    if m:
        parent = m.group(1).lower()
        return strength(raw[parent][0], table, raw)
    if "instabreak()" in reg:
        return 0.0, 0.0
    m = re.search(r"strength\(([-0-9.]+)F(?:, ([-0-9.]+)F)?\)", reg)
    if not m:
        raise SystemExit("no strength in " + reg)
    h = float(m.group(1))
    r = float(m.group(2)) if m.group(2) else h
    return h, r


def main():
    raw = rows()
    lines = ["// Generated by tools/structures/building/blocktable.py from docs/spec/building.md (Appendix A):",
             "// {id, hardness, explosion resistance (Java units), tool tag (\"\": none), tier tag (\"\": none)}."]
    for bid in sorted(raw):
        reg, notes = raw[bid]
        h, r = strength(reg, raw, raw)
        tool = next((t for t in TOOLS if "#mc:mineable/%s" % t in notes), "")
        tier = next((t for t in TIERS if "#mc:needs_%s_tool" % t in notes), "")
        lines.append('{"%s", %sf, %sf, "%s", "%s"},' % (bid, repr(h), repr(r), tool, tier))
    files = {OUT: "\n".join(lines) + "\n", OUT_CUT: stonecutting()}
    stale = []
    for path, text in files.items():
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old == text:
            continue
        if "--check" in sys.argv:
            stale.append(os.path.relpath(path, ROOT))
            continue
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, ROOT))
    if stale:
        print("stale:", *stale, sep="\n  ")
        sys.exit(1)


def stonecutting():
    """The unit's stonecutting recipes (Appendix A, Recipes): {input, output, count}."""
    with open(SPEC, encoding="utf-8") as f:
        text = f.read()
    lines = ["// Generated by tools/structures/building/blocktable.py from docs/spec/building.md (Appendix A):",
             "// the unit's stonecutting recipes {input, output, count}."]
    for line in text.splitlines():
        cells = [c.strip() for c in line.split("|")]
        if len(cells) < 6 or cells[2] != "mc:stonecutting":
            continue
        m = re.match(r"^((?:mc:)?[a-z_0-9]+)(?: x(\d+))?$", cells[4])
        if not m or not re.match(r"^(mc:)?[a-z_0-9]+$", cells[3]):
            raise SystemExit("unexpected stonecutting row: " + line)

        def full(i):
            return "minecraft:" + i[3:] if i.startswith("mc:") else "twilightforest:" + i
        lines.append('{"%s", "%s", %d},' % (full(cells[3]), full(m.group(1)), int(m.group(2) or 1)))
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    main()

# Contract "synth" (F3): TF's sound event inventory, dot-sourced by tools/sounds/*.ps1 (after
# lib/SynthJson.ps1).
#
# tools/sounds/baseline/inventory.json is written by tools/sounds/baseline/generate.ps1 from TF's
# sounds.json alone (never from recipes): per event its owner, Bedrock category, subtitle key and
# TF's variants flattened through event references ({volume, pitch, stream} of each sound a play
# can pick; a vanilla event counts the Bedrock files it maps to in tools/sounds/vanilla.json).
# tools/sounds/synth.ps1 checks every rendered definition against it, and the synth.definitions
# selftest checks the assembled resource pack against src/feature/ext/synth/SoundEvents.inc, the
# same inventory in C++ (Format-SoundEventsInc).

# One-line JSON (Format-Json without line breaks).
function Format-JsonLine($v) { return ((Format-Json $v) -replace ",\n\s*", ', ' -replace "\n\s*", '') }

function Format-Inventory($inventory) {
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('{')
    $lines.Add('  "about": ' + (Format-Json $inventory.about) + ',')
    $lines.Add('  "events": {')
    $keys = @($inventory.events.Keys)
    for ($i = 0; $i -lt $keys.Count; $i++) {
        $sep = if ($i -lt $keys.Count - 1) { ',' } else { '' }
        $lines.Add('    ' + (Format-Json ([string]$keys[$i])) + ': ' + (Format-JsonLine $inventory.events[$keys[$i]]) + $sep)
    }
    $lines.Add('  }')
    $lines.Add('}')
    return ($lines -join "`n") + "`n"
}

function Read-Inventory([string]$path) {
    if (-not (Test-Path $path)) { throw "$path is missing: run pwsh tools/sounds/baseline/generate.ps1" }
    return Get-Content -LiteralPath $path -Raw | ConvertFrom-Json -AsHashtable
}

function Format-CppDouble([double]$d) {
    $s = $d.ToString('R', [Globalization.CultureInfo]::InvariantCulture)
    if ($s -notmatch '[.eE]') { $s += '.0' }
    return $s
}

function Format-CppString([string]$s) { return '"' + $s.Replace('\', '\\').Replace('"', '\"') + '"' }

# The C++ form of the inventory (src/feature/ext/synth/SoundEvents.inc).
function Format-SoundEventsInc($inventory) {
    $lines = [Collections.Generic.List[string]]::new()
    $lines.Add('// Generated by tools/sounds/baseline/generate.ps1 from TF''s sounds.json (tools/sounds/baseline/inventory.json): do not edit.')
    $lines.Add('// GF_SOUND_EVENT(event, owner unit, category, subtitle key or "", variant count), followed by its variants:')
    $lines.Add('// GF_SOUND_VARIANT(volume, pitch, stream), TF''s attributes of each sound a play can pick.')
    foreach ($e in ($inventory.events.Keys | Sort-Object)) {
        $ev   = $inventory.events[$e]
        $sub  = if ($ev.Contains('subtitle')) { [string]$ev.subtitle } else { '' }
        $vars = @($ev.variants)
        $lines.Add("GF_SOUND_EVENT($(Format-CppString $e), $(Format-CppString $ev.owner), $(Format-CppString $ev.category), $(Format-CppString $sub), $($vars.Count))")
        foreach ($v in $vars) {
            $stream = if ($v.Contains('stream') -and $v.stream) { 'true' } else { 'false' }
            $lines.Add("GF_SOUND_VARIANT($(Format-CppDouble $v.volume), $(Format-CppDouble $v.pitch), $stream)")
        }
    }
    return ($lines -join "`n") + "`n"
}

# Sorted "volume|pitch|stream" keys of a variant list (the order of a definition's sounds does not
# matter: a play picks one at random).
function Get-VariantKeys($variants) {
    $keys = foreach ($v in @($variants)) {
        $vol = if ($v.Contains('volume') -and $null -ne $v['volume']) { [double]$v['volume'] } else { 1.0 }
        $pit = if ($v.Contains('pitch') -and $null -ne $v['pitch']) { [double]$v['pitch'] } else { 1.0 }
        $str = [bool]($v.Contains('stream') -and $v['stream'])
        '{0}|{1}|{2}' -f [math]::Round($vol, 6).ToString([Globalization.CultureInfo]::InvariantCulture), [math]::Round($pit, 6).ToString([Globalization.CultureInfo]::InvariantCulture), $str.ToString().ToLower()
    }
    return @($keys | Sort-Object)
}
